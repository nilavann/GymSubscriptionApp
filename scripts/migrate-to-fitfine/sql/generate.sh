#!/usr/bin/env bash
# Regenerates sql/01-pre-data.sql and sql/02-post-data.sql from a read-only, schema-only pg_dump
# of the 11 source tables (MIG-1.1). Keeps tables, CHECK/NOT NULL, defaults, identity columns,
# keys, FKs and indexes; drops every other dump entry (triggers, policies, RLS, ...).
# The schema is written as the psql variable :"schema", which run.sh sets to TARGET_SCHEMA.
# Usage: sql/generate.sh   (MIG_ENV_FILE as for run.sh; writes nothing to either database)
set -euo pipefail
MIG_DIR=$(cd "$(dirname "$0")/.." && pwd)
. "$MIG_DIR/lib/common.sh"
load_env "${MIG_ENV_FILE:-$MIG_DIR/.env}"
require_vars SOURCE_DB_URL

KEEP_PRE='TABLE|SEQUENCE'
KEEP_POST='CONSTRAINT|FK CONSTRAINT|INDEX'

tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
tables=()
for t in $(mig_tables); do tables+=("--table=public.$t"); done

# Prints only the dump entries ("-- Name: ...; Type: X; ...") whose type is in $2, with
# public. qualifiers replaced by :"schema". and the pg_dump session preamble left out.
filter() {
  awk -v keep="^($2)\$" '
    /^-- Name: .*; Type: / {
      type = $0; sub(/.*; Type: /, "", type); sub(/;.*/, "", type)
      keeping = (type ~ keep)
      if (keeping) print ""
    }
    /^-- PostgreSQL database dump complete/ { keeping = 0 }
    !keeping || $0 == "--" { next }
    /^-- Name: / { name = $0; sub(/^-- Name: /, "", name); sub(/; Type: .*/, "", name); print "-- " type ": " name; next }
    { print }
  ' "$1" | sed -E 's/(^|[^[:alnum:]_"])public\./\1:"schema"./g' | cat -s
}

for section in pre-data post-data; do
  PGOPTIONS="-c default_transaction_read_only=on" pg_dump --schema-only --no-owner --no-privileges \
    --section=$section "${tables[@]}" -d "$SOURCE_DB_URL" >"$tmp/$section.sql"
done
version=$(sed -nE 's/^-- Dumped from database version (.*)/\1/p' "$tmp/pre-data.sql")

{
  cat <<EOF
-- Generated by sql/generate.sh from a schema-only pg_dump of the source (PostgreSQL $version).
-- Do not edit by hand: rerun the generator. Applied by run.sh --create with -v schema=TARGET_SCHEMA.
-- Pre-data: the 11 tables with columns, defaults, NOT NULL, CHECK and identity columns. No keys,
-- FKs or indexes (02-post-data.sql adds those after the load), no triggers, policies or RLS.

CREATE SCHEMA :"schema";
EOF
  filter "$tmp/pre-data.sql" "$KEEP_PRE"
} >"$MIG_DIR/sql/01-pre-data.sql"

{
  cat <<EOF
-- Generated by sql/generate.sh from a schema-only pg_dump of the source (PostgreSQL $version).
-- Do not edit by hand: rerun the generator. Applied by run.sh --load, inside the load transaction,
-- after every table has its rows, so adding each FK checks every reference.
-- Post-data: primary keys, foreign keys and indexes. No triggers, policies or RLS.
EOF
  filter "$tmp/post-data.sql" "$KEEP_POST"
} >"$MIG_DIR/sql/02-post-data.sql"

# Every dump entry is either kept or listed here as deliberately dropped; anything else stops.
unknown=$(grep -hoE '^-- Name: .*; Type: [A-Z ]+;' "$tmp/pre-data.sql" "$tmp/post-data.sql" |
  sed -E 's/.*Type: ([A-Z ]+);/\1/' | sort -u | grep -vxE "$KEEP_PRE|$KEEP_POST|TRIGGER|POLICY|ROW SECURITY" || true)
[ -z "$unknown" ] || die "dump has entry types neither kept nor known-dropped: $unknown"

log "wrote sql/01-pre-data.sql ($(grep -c '^CREATE TABLE' "$MIG_DIR/sql/01-pre-data.sql") tables)"
log "wrote sql/02-post-data.sql ($(grep -cE 'PRIMARY KEY' "$MIG_DIR/sql/02-post-data.sql") primary keys," \
  "$(grep -c 'FOREIGN KEY' "$MIG_DIR/sql/02-post-data.sql") foreign keys, $(grep -c '^CREATE .*INDEX' "$MIG_DIR/sql/02-post-data.sql") indexes)"
